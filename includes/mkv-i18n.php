// Hàm lấy ngôn ngữ hiện tại của user (vi hoặc en)
function mkv_get_current_lang() {
    $user_id = get_current_user_id();
    if (!$user_id) return 'vi'; // Mặc định là Tiếng Việt
    
    $lang = get_user_meta($user_id, 'mkv_user_lang', true);
    return $lang === 'en' ? 'en' : 'vi';
}

