// API xử lý đổi ngôn ngữ bằng AJAX
add_action('wp_ajax_mkv_switch_lang', 'mkv_switch_lang_callback');
function mkv_switch_lang_callback() {
    $lang = isset($_POST['lang']) ? sanitize_text_field($_POST['lang']) : 'vi';
    $user_id = get_current_user_id();
    
    if ($user_id && in_array($lang, ['vi', 'en'])) {
        update_user_meta($user_id, 'mkv_user_lang', $lang);
        wp_send_json_success(array('lang' => $lang));
    }
    wp_send_json_error();
}
