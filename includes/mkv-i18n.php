// Hàm lấy ngôn ngữ hiện tại của user (vi hoặc en)
function mkv_get_current_lang() {
    // 1. Kiểm tra cookie trước để đảm bảo phản hồi tức thì sau khi người dùng click
    if (isset($_COOKIE['mkv_lang']) && in_array($_COOKIE['mkv_lang'], ['vi', 'en'], true)) {
        return $_COOKIE['mkv_lang'];
    }
    // 2. Fallback sang user meta nếu chưa có cookie trên trình duyệt hiện tại
    $user_id = get_current_user_id();
    if ($user_id) {
        $lang = get_user_meta($user_id, 'mkv_user_lang', true);
        if ($lang && in_array($lang, ['vi', 'en'], true)) {
            return $lang;
        }
    }
    return 'vi';
}

